buku = 7
halaman_per_buku = 120

print("Total halaman:", buku * halaman_per_buku)
print("Bagi:", buku / 2)
print("Bagi bulat:", buku // 2)
print("Sisa bagi 5:", buku % 5)
print("Pangkat:", buku ** 2)
print("Lebih dari 5?", buku > 5)
print("Sama dengan 7?", buku == 7)
print("Logika:", buku > 5 and halaman_per_buku < 200)
